// Подсказка для неизвестного OID: чья это ветка по реестру
function registryHint(oid) {
  for (let o = oid; o.includes('.'); o = o.slice(0, o.lastIndexOf('.'))) {
    if (REGISTRY[o]) return o === oid ? `OID организации: ${REGISTRY[o]}` : `Ветка ${o} — ${REGISTRY[o]}`;
    if (o.split('.').length <= 4) break;
  }
  return null;
}

